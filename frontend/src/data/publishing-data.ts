// Helper functions
export function getProjectById(id: string): PublishingProject | undefined {
  return publishingProjects.find(p => p.id === id);
}

export function getProjectsByStatus(status: SubmissionStatus): PublishingProject[] {
  return publishingProjects.filter(p => p.status === status);
}

export function getProjectsByApplication(applicationId: string): PublishingProject[] {
  return publishingProjects.filter(p => p.applicationId === applicationId);
}

export function calculateProjectProgress(project: PublishingProject): number {
  const totalModules = project.modules.length;
  const completeModules = project.modules.filter(m => m.status === 'complete').length;
  const partialModules = project.modules.filter(m => m.status === 'partial').length;
  return Math.round(((completeModules + partialModules * 0.5) / totalModules) * 100);
}
