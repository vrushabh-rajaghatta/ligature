// Helper functions
export function getQuestionsByApplication(applicationId: string): HAQuestion[] {
  return haqQuestions.filter(q => q.applicationId === applicationId);
}

export function getQuestionsByStatus(status: HAQStatus): HAQuestion[] {
  return haqQuestions.filter(q => q.status === status);
}

export function getQuestionsByDiscipline(discipline: HAQDiscipline): HAQuestion[] {
  return haqQuestions.filter(q => q.discipline === discipline);
}

export function getOverdueQuestions(): HAQuestion[] {
  const today = new Date();
  return haqQuestions.filter(q => {
    const dueDate = new Date(q.dueDate);
    return dueDate < today && !['submitted', 'closed'].includes(q.status);
  });
}

export function getSimilarQuestionsForHAQ(haqId: string): SimilarQuestion[] {
  const question = haqQuestions.find(q => q.id === haqId);
  if (!question) return [];
  return similarQuestions.filter(sq => sq.discipline === question.discipline);
}

